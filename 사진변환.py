정보파일후보 = [
    기준폴더 / "자료" / "가게 정보.txt",
    기준폴더 / "가게 정보.txt",
    기준폴더 / "가게정보.txt",
    기준폴더 / "자료" / "가게정보.txt",
]


def 가게정보읽기():
    """가게 정보 파일을 읽어 항목별로 정리. 파일이 없으면 None."""
    for 경로 in 정보파일후보:
        if not 경로.is_file():
            continue
        글 = 경로.read_text(encoding="utf-8-sig")
        정보 = {"이름": "", "위치": "", "특징": "", "홍보": []}
        홍보구간 = False
        for 줄 in 글.splitlines():
            줄 = 줄.strip()
            if not 줄:
                continue
            if 줄.startswith("가게 이름:"):
                정보["이름"] = 줄.split(":", 1)[1].strip()
            elif 줄.startswith("위치:"):
                정보["위치"] = 줄.split(":", 1)[1].strip()
            elif 줄.startswith("가게 특징:"):
                정보["특징"] = 줄.split(":", 1)[1].strip()
            elif 줄.startswith("이번 주 홍보할 것"):
                홍보구간 = True
            elif 줄.startswith("말투 느낌"):
                홍보구간 = False
            elif 홍보구간 and 줄.startswith("-"):
                정보["홍보"].append(줄.lstrip("- ").strip())
        return 정보
    return None


def 문장체로(조각):
    """'넣음', '않음' 같은 메모체를 '넣었습니다', '않습니다'로 바꿈."""
    조각 = 조각.strip()
    if 조각.endswith("않음"):
        return 조각[:-2] + "않습니다."
    if 조각.endswith("음") and len(조각) > 1:
        return 조각[:-1] + "었습니다."
    return 조각 + "."


def 홍보내용나누기(정보):
    """홍보 항목에서 신메뉴 / 할인(이벤트) / 나머지를 골라냄."""
    메뉴 = 가격 = 설명 = 이벤트 = ""
    기타 = []
    for 항목 in 정보["홍보"]:
        신메뉴 = re.match(r"신메뉴\s*['\"‘“](.+?)['\"’”]\s*([\d,]+원)?\s*,?\s*(.*)", 항목)
        if 신메뉴 and not 메뉴:
            메뉴, 가격, 나머지 = 신메뉴.group(1), 신메뉴.group(2) or "", 신메뉴.group(3)
            설명 = " ".join(문장체로(c) for c in 나머지.split(",") if c.strip())
        elif ("할인" in 항목 or "이벤트" in 항목) and not 이벤트:
            이벤트 = 항목
        else:
            기타.append(항목)
    return 메뉴, 가격, 설명, 이벤트, 기타


def 해시태그만들기(정보, 메뉴, 이벤트):
    """지역명 + 업종 + 메뉴를 섞어 10개."""
    위치말 = [w for w in 정보["위치"].split() if w not in ("지구", "일대", "근처")]
    태그 = []
    if len(위치말) >= 2:
        태그 += [위치말[0], 위치말[0] + 위치말[1]] + 위치말[2:]  # 예: 광주, 광주북구, 비엔날레
    else:
        태그 += 위치말
    글 = 정보["이름"] + " " + 정보["특징"]
    카페 = "커피" in 글 or "카페" in 글
    if 카페:
        태그 += ["카페", "커피"]
        if "스페셜티" in 글:
            태그.append("스페셜티커피")
    if 메뉴:
        태그 += [메뉴.replace(" ", ""), "신메뉴"]
    if 이벤트 and "아메리카노" in 이벤트:
        태그.append("아메리카노")
    if 위치말 and 카페:
        태그.append(위치말[0] + "카페")
    if 카페:
        태그 += ["카페추천", "로스터리"] if "로스팅" in 글 else ["카페추천"]
    # 중복 제거 후 10개까지, 모자라면 일반 태그로 채움
    결과 = []
    for t in 태그 + ["오늘의카페", "카페스타그램", "커피스타그램", "일상", "맛집추천"]:
        if t and t not in 결과:
            결과.append(t)
    return " ".join("#" + t for t in 결과[:10])


def 문구만들기(정보):
    """감성형 / 정보형 / 이벤트형 x 인스타그램 / 네이버 블로그 / 카카오톡 단골 공지 = 9개."""
    가게 = 정보["이름"] or "저희 가게"
    위치 = 정보["위치"]
    메뉴, 가격, 설명, 이벤트, 기타 = 홍보내용나누기(정보)
    if 메뉴:
        신메뉴 = f"신메뉴 '{메뉴}'" + (f"({가격})" if 가격 else "")
    else:
        신메뉴 = 기타[0] if 기타 else "이번 주 소식"
    설명 = 설명 or ""
    이벤트문 = 이벤트 or (기타[0] if 기타 and not 메뉴 else "")
    특징 = [c.strip() for c in 정보["특징"].split(",") if c.strip()]
    특징1 = 특징[0] if 특징 else ""
    특징2 = 특징[1] if len(특징) > 1 else ""
    태그 = 해시태그만들기(정보, 메뉴, 이벤트)

    # 사장님 말투: 이모지 없이, 짧은 문장을 한 줄에 하나씩, 문단 사이는 한 줄 비움
    설명줄 = re.findall(r"[^.]+\.", 설명)
    첫설명 = 설명줄[0].strip() if 설명줄 else ""
    소개 = f"{위치}에 있는 " if 위치 else ""
    특징문 = ""
    if 특징1 and 특징2:
        특징문 = f"저희 가게의 특징은 '{특징1}'와 '{특징2}'입니다."
    elif 특징1:
        특징문 = f"저희 가게의 특징은 '{특징1}'입니다."
    할인문 = f"{이벤트문}입니다." if 이벤트문 else ""
    새메뉴문 = f"{신메뉴}가 나왔습니다."

    def 글(*문단들):
        """문단(문장 목록)들을 줄바꿈으로 이어 붙임. 빈 문장/문단은 건너뜀."""
        덩어리 = []
        for 문단 in 문단들:
            줄 = [x.strip() for x in 문단 if x and x.strip()]
            if 줄:
                덩어리.append("\n".join(줄))
        return "\n\n".join(덩어리)

    문구 = {
        # ---- 인스타그램 (해시태그는 저장할 때 아래에 붙음) ----
        ("감성형", "인스타그램"): 글(
            [f"{가게}입니다."],
            [새메뉴문, *설명줄],
            ["조용히 쉬다 가시면 좋겠습니다."],
        ),
        ("정보형", "인스타그램"): 글(
            [f"{가게} 이번 주 소식입니다."],
            [새메뉴문, *설명줄],
            [할인문],
            [f"위치는 {위치}입니다." if 위치 else ""],
        ),
        ("이벤트형", "인스타그램"): 글(
            ["이번 주 혜택을 안내드립니다."],
            [할인문],
            [f"{신메뉴}도 나왔습니다.", *설명줄],
            ["오시면 편하게 드세요."],
        ),
        # ---- 네이버 블로그 (300자 정도, 해시태그 없음) ----
        ("감성형", "네이버 블로그"): 글(
            [f"안녕하세요, {소개}{가게}입니다."],
            ["바쁜 하루 중에 잠깐 쉴 자리가 필요할 때가 있습니다.",
             "저희 가게가 그런 자리가 되었으면 합니다."],
            [특징문],
            [f"이번 주에는 {신메뉴}를 준비했습니다.", *설명줄],
            [f"그리고 {할인문}" if 할인문 else ""],
            ["조용히 쉬다 가시면 좋겠습니다.", "기다리고 있겠습니다."],
        ),
        ("정보형", "네이버 블로그"): 글(
            [f"안녕하세요, {소개}{가게}입니다.", "이번 주 소식을 정리해서 알려드립니다."],
            [특징문],
            [f"먼저 {새메뉴문}", *설명줄],
            [f"그리고 {할인문}" if 할인문 else ""],
            [f"위치는 {위치}입니다." if 위치 else "", "근처에 오시면 들러주세요."],
        ),
        ("이벤트형", "네이버 블로그"): 글(
            [f"안녕하세요, {소개}{가게}입니다.", "이번 주 혜택을 미리 알려드립니다."],
            [할인문, "출근길에 한 잔 하고 가시면 됩니다." if 이벤트문 else ""],
            [f"{신메뉴}도 새로 나왔습니다.", *설명줄],
            [특징문],
            ["부담 없이 오세요.", "기다리고 있겠습니다."],
        ),
        # ---- 카카오톡 단골 공지 (3줄 이내, 존댓말) ----
        ("감성형", "카카오톡 단골 공지"): (
            f"{가게}입니다.\n"
            f"{새메뉴문} {첫설명}\n"
            f"조용히 쉬다 가세요."
        ),
        ("정보형", "카카오톡 단골 공지"): (
            f"{가게} 이번 주 소식입니다.\n"
            f"{새메뉴문} {첫설명}\n"
            + (할인문 if 할인문 else f"위치는 {위치}입니다.")
        ),
        ("이벤트형", "카카오톡 단골 공지"): (
            f"단골손님께 안내드립니다.\n"
            + (f"{할인문}\n" if 할인문 else "")
            + f"{신메뉴}도 나왔으니 오세요."
        ),
    }
    return 문구, 태그


def 문구저장():
    정보 = 가게정보읽기()
    if 정보 is None:
        print("'가게 정보.txt' 파일이 없어서 홍보 문구는 건너뛰었어요.")
        return
    문구, 태그 = 문구만들기(정보)
    완성폴더.mkdir(exist_ok=True)

    줄들 = [f"{정보['이름']} 홍보 문구 ({date.today().isoformat()})", "=" * 40]
    for 종류 in ("감성형", "정보형", "이벤트형"):
        줄들 += ["", f"■ {종류}"]
        for 채널 in ("인스타그램", "네이버 블로그", "카카오톡 단골 공지"):
            글 = 문구[(종류, 채널)]
            줄들 += ["", f"[{채널}용] ({len(글.replace(chr(10), ''))}자)", 글]
            if 채널 == "인스타그램":
                줄들 += ["", 태그]
    저장경로 = 완성폴더 / "홍보문구.txt"
    저장경로.write_text("\n".join(줄들) + "\n", encoding="utf-8-sig")
    print(f"홍보 문구를 만들었어요: {저장경로.name}")


def main():
    사진처리()
    문구저장()
    print("끝! '완성' 폴더를 확인해 보세요.")


if __name__ == "__main__":
    main()
