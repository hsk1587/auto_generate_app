"""매장 사진을 인스타그램용 1080x1080 정사각형으로 바꿔주는 프로그램.

- '사진' 폴더의 jpg, png 파일을 읽기만 합니다 (원본은 건드리지 않음)
- 가운데를 기준으로 정사각형으로 잘라 1080x1080으로 맞춥니다
- '완성' 폴더에 '오늘날짜_번호.jpg'로 저장합니다
"""
import re
from datetime import date
from pathlib import Path

from PIL import Image, ImageOps

크기 = 1080
기준폴더 = Path(__file__).resolve().parent
사진폴더 = 기준폴더 / "사진"
완성폴더 = 기준폴더 / "완성"
확장자 = {".jpg", ".jpeg", ".png"}

# 로고 설정 (없으면 로고 넣기를 건너뜀)
로고후보 = [
    기준폴더 / "자료" / "로고.png",
    기준폴더 / "로고.png",
    기준폴더 / "로고.jpg",
    기준폴더 / "자료" / "로고.jpg",
]
로고비율 = 0.15   # 사진 가로 폭의 15%
로고여백 = 40     # 가장자리에서 안쪽으로 40픽셀
로고판여백 = 16   # 로고 둘레 흰색 여백(픽셀)


def 로고불러오기():
    """로고 파일을 찾아 알맞은 크기로 줄여서 돌려줌. 없거나 못 읽으면 None."""
    for 경로 in 로고후보:
        if not 경로.is_file():
            continue
        try:
            with Image.open(경로) as 파일:
                로고 = ImageOps.exif_transpose(파일).convert("RGBA")
            가로 = round(크기 * 로고비율)
            세로 = max(1, round(로고.height * 가로 / 로고.width))
            로고 = 로고.resize((가로, 세로), Image.LANCZOS)
            # 흰색 네모 판 위에 로고를 올려서 어떤 배경에서도 눈에 띄게 함
            판 = Image.new("RGBA", (가로 + 로고판여백 * 2, 세로 + 로고판여백 * 2), (255, 255, 255, 255))
            판.paste(로고, (로고판여백, 로고판여백), 로고)
            로고 = 판
            print(f"로고를 넣을게요: {경로.name}")
            return 로고
        except Exception as 오류:
            print(f"로고를 읽지 못해서 로고 없이 진행해요: {오류}")
            return None
    print("로고 파일이 없어서 로고 없이 진행해요.")
    return None


def 다음번호(오늘):
    """완성 폴더에 오늘 날짜 파일이 이미 있으면 그 다음 번호부터 시작."""
    가장큰번호 = 0
    for 파일 in 완성폴더.glob(f"{오늘}_*.jpg"):
        맞음 = re.fullmatch(rf"{오늘}_(\d+)", 파일.stem)
        if 맞음:
            가장큰번호 = max(가장큰번호, int(맞음.group(1)))
    return 가장큰번호 + 1


def 사진처리():
    사진폴더.mkdir(exist_ok=True)
    완성폴더.mkdir(exist_ok=True)

    사진들 = sorted(
        p for p in 사진폴더.iterdir() if p.is_file() and p.suffix.lower() in 확장자
    )
    if not 사진들:
        print("'사진' 폴더에 jpg, png 사진이 없어요. 사진을 넣고 다시 실행해 주세요.")
        return

    오늘 = date.today().isoformat()
    번호 = 다음번호(오늘)
    로고 = 로고불러오기()

    for 사진 in 사진들:
        try:
            with Image.open(사진) as 원본:
                # 휴대폰 사진의 회전 정보를 반영 (눕혀 보이는 문제 방지)
                그림 = ImageOps.exif_transpose(원본).convert("RGB")
                # 가운데 기준으로 비율 유지하며 잘라서 1080x1080으로 맞춤
                결과 = ImageOps.fit(그림, (크기, 크기), Image.LANCZOS, centering=(0.5, 0.5))
                if 로고 is not None:
                    위치 = (크기 - 로고.width - 로고여백, 크기 - 로고.height - 로고여백)
                    결과.paste(로고, 위치, 로고)
                저장경로 = 완성폴더 / f"{오늘}_{번호:02d}.jpg"
                결과.save(저장경로, "JPEG", quality=95)
            print(f"{사진.name} -> {저장경로.name}")
            번호 += 1
        except Exception as 오류:
            print(f"{사진.name} 은(는) 건너뛰었어요 (읽을 수 없는 사진): {오류}")

    print("사진 변환 끝!")


